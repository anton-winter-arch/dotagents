@unittest.skipUnless(HAVE_FFMPEG, "ffmpeg not installed")
class TestCli(unittest.TestCase):
    def setUp(self):
        self._work = tempfile.TemporaryDirectory()
        self.dir = Path(self._work.name)
        for name in ("video.mov", "photo.png"):
            shutil.copy(FIX / name, self.dir / name)
        (self.dir / "notes.txt").write_text("not media")
        shutil.copy(FIX / "base.jpg", self.dir / "earlier_small.jpg")

    def tearDown(self):
        self._work.cleanup()

    def cli(self, *args, env=None):
        return subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True, env=env)

    def snapshot(self):
        return {p.name: digest(p) for p in self.dir.iterdir()}

    def test_folder_run_is_idempotent(self):
        r = self.cli(str(self.dir))
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertTrue((self.dir / "video_small.mp4").exists())
        self.assertTrue((self.dir / "photo_small.jpg").exists())
        self.assertFalse((self.dir / "earlier_small_small.jpg").exists())
        self.assertIn("2 done", r.stdout)
        first = self.snapshot()
        again = self.cli(str(self.dir))
        self.assertEqual(again.returncode, 0)
        self.assertIn("2 exists", again.stdout)
        self.assertEqual(self.snapshot(), first)

    def test_dry_run_writes_nothing(self):
        before = self.snapshot()
        r = self.cli(str(self.dir), "--dry-run", "--max-size", "5MB")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("ffmpeg ", r.stdout)
        self.assertIn("under 5.0 MB", r.stdout)
        self.assertEqual(self.snapshot(), before)

    def test_json_output(self):
        r = self.cli(str(self.dir / "photo.png"), "--to", "webp", "--json")
        self.assertEqual(r.returncode, 0, r.stderr)
        (result,) = json.loads(r.stdout)
        self.assertEqual((result["status"], result["target"]), ("done", "webp"))

    def test_unsupported_explicit_file_exits_1(self):
        r = self.cli(str(self.dir / "notes.txt"))
        self.assertEqual(r.returncode, 1)
        self.assertIn("unsupported", r.stdout)

    def test_bad_target_exits_2(self):
        r = self.cli(str(self.dir), "--to", "divx")
        self.assertEqual(r.returncode, 2)
        self.assertIn("unknown target", r.stderr)

    def test_symlinked_source_writes_beside_the_link(self):
        elsewhere = self.dir / "elsewhere"
        elsewhere.mkdir()
        shutil.move(str(self.dir / "photo.png"), elsewhere / "photo.png")
        linked = self.dir / "linked"
        linked.mkdir()
        (linked / "shot.png").symlink_to(elsewhere / "photo.png")
        r = self.cli(str(linked))
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertTrue((linked / "shot_small.jpg").exists())
        self.assertEqual(sorted(p.name for p in elsewhere.iterdir()), ["photo.png"])

    def test_two_sources_never_share_an_output(self):
        shutil.copy(FIX / "hdr.mp4", self.dir / "video.mp4")
        r = self.cli(str(self.dir / "video.mov"), str(self.dir / "video.mp4"), "--force")
        self.assertEqual(r.returncode, 1, r.stdout)
        self.assertIn("already writes video_small.mp4", r.stdout)

    def test_output_never_replaces_a_named_source(self):
        shutil.copy(FIX / "hdr.mp4", self.dir / "video_small.mp4")
        before = digest(self.dir / "video_small.mp4")
        r = self.cli(str(self.dir / "video.mov"), str(self.dir / "video_small.mp4"), "--force")
        self.assertEqual(r.returncode, 1, r.stdout)
        self.assertIn("would replace a source file", r.stdout)
        self.assertEqual(digest(self.dir / "video_small.mp4"), before)

    def test_missing_ffmpeg_exits_2_with_install_hint(self):
        r = self.cli(str(self.dir), env={**os.environ, "PATH": str(self.dir)})
        self.assertEqual(r.returncode, 2)
        self.assertIn("brew install ffmpeg", r.stderr)


