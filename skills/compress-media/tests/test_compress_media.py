class TestCollect(unittest.TestCase):
    def test_folder_expansion(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            for name in ("a.mov", "b_small.mp4", "notes.txt", ".hidden/c.mov", "sub/d.png"):
                (root / name).parent.mkdir(parents=True, exist_ok=True)
                (root / name).write_bytes(b"")
            flat, _ = cm.collect([str(root)], recursive=False)
            self.assertEqual([p.name for p in flat], ["a.mov"])
            deep, _ = cm.collect([str(root)], recursive=True)
            self.assertEqual(sorted(p.name for p in deep), ["a.mov", "d.png"])

    def test_missing_path_is_reported(self):
        files, missing = cm.collect(["/no/such/file.mov"], recursive=False)
        self.assertEqual(files, [])
        self.assertEqual(missing[0]["status"], "failed")

    def test_duplicates_collapse(self):
        with tempfile.TemporaryDirectory() as d:
            f = Path(d) / "a.mov"
            f.write_bytes(b"")
            files, _ = cm.collect([str(f), str(f), d], recursive=False)
            self.assertEqual(len(files), 1)


