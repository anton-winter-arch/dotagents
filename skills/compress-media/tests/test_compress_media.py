@unittest.skipUnless(HAVE_FFMPEG, "ffmpeg not installed")
class TestCompress(unittest.TestCase):
    def setUp(self):
        self._work = tempfile.TemporaryDirectory()
        self.out = Path(self._work.name)

    def tearDown(self):
        self._work.cleanup()

    def run_one(self, name, to=None, quality="medium", max_size=0, force=False):
        src = FIX / name
        before = digest(src)
        r = cm.compress(src, to, quality, max_size, self.out, force, False)
        self.assertEqual(digest(src), before, "the source must never change")
        self.assertFalse(any(p.name.startswith(".compress-media-") for p in self.out.iterdir()),
                         "the work folder must be cleaned up")
        return r

    def test_video_default_is_smaller_hevc(self):
        r = self.run_one("video.mov")
        self.assertEqual((r["status"], r["target"]), ("done", "hevc"), r["note"])
        self.assertLess(r["after"], r["before"])
        v, a = streams(r["output"])
        self.assertEqual((v["codec_name"], v["codec_tag_string"]), ("hevc", "hvc1"))
        self.assertEqual(a["codec_name"], "aac")

    def test_odd_dimensions_become_even(self):
        r = self.run_one("odd.mov", to="h264")
        self.assertEqual(r["status"], "done", r["note"])
        (v,) = streams(r["output"])
        self.assertEqual((v["width"], v["height"]), (320, 240))

    def test_hdr_is_kept_in_hevc(self):
        r = self.run_one("hdr.mp4", to="hevc", quality="low")
        self.assertEqual(r["status"], "done", r["note"])
        (v,) = streams(r["output"])
        self.assertEqual((v["pix_fmt"], v["color_transfer"]), ("yuv420p10le", "arib-std-b67"))

    def test_hdr_is_tonemapped_for_h264(self):
        r = self.run_one("hdr.mp4", to="h264")
        self.assertEqual(r["status"], "done", r["note"])
        (v,) = streams(r["output"])
        self.assertEqual((v["pix_fmt"], v["color_transfer"]), ("yuv420p", "bt709"))

    def test_av1_webm(self):
        r = self.run_one("video.mov", to="av1")
        self.assertEqual(r["status"], "done", r["note"])
        self.assertTrue(r["output"].endswith(".webm"))
        self.assertEqual([s["codec_name"] for s in streams(r["output"])], ["av1", "opus"])

    def test_audio_default(self):
        r = self.run_one("audio.wav")
        self.assertEqual((r["status"], r["target"]), ("done", "aac"), r["note"])
        self.assertTrue(r["output"].endswith(".m4a"))
        self.assertLess(r["after"], r["before"])

    def test_audio_extracted_from_video(self):
        r = self.run_one("video.mov", to="mp3")
        self.assertEqual(r["status"], "done", r["note"])
        self.assertEqual([s["codec_type"] for s in streams(r["output"])], ["audio"])

    def test_result_that_is_not_smaller_is_discarded(self):
        r = self.run_one("low.opus")
        self.assertEqual(r["status"], "kept-original")
        self.assertIsNone(r["output"])
        self.assertEqual(list(self.out.iterdir()), [])

    def test_explicit_target_keeps_a_larger_result(self):
        r = self.run_one("low.opus", to="aac")
        self.assertEqual(r["status"], "done", r["note"])
        self.assertIn("larger", r["note"])
        self.assertTrue(Path(r["output"]).exists())

    def test_png_to_jpeg(self):
        r = self.run_one("photo.png")
        self.assertEqual((r["status"], r["target"]), ("done", "jpeg"), r["note"])
        self.assertEqual(streams(r["output"])[0]["codec_name"], "mjpeg")

    def test_transparent_png_keeps_alpha_in_webp(self):
        r = self.run_one("alpha.png")
        self.assertEqual((r["status"], r["target"]), ("done", "webp"), r["note"])
        self.assertTrue(streams(r["output"])[0]["pix_fmt"].startswith("yuva"))

    def test_transparent_png_flattens_into_jpeg(self):
        r = self.run_one("alpha.png", to="jpeg")
        self.assertEqual(r["status"], "done", r["note"])

    def test_png_to_avif(self):
        r = self.run_one("photo.png", to="avif")
        self.assertEqual(r["status"], "done", r["note"])
        self.assertEqual(streams(r["output"])[0]["codec_name"], "av1")

    def test_exif_rotation_is_applied(self):
        r = self.run_one("rot.jpg", to="webp")
        self.assertEqual(r["status"], "done", r["note"])
        s = streams(r["output"])[0]
        self.assertEqual((s["width"], s["height"]), (48, 64))

    def test_gif_to_mp4(self):
        r = self.run_one("anim.gif")
        self.assertEqual((r["status"], r["target"]), ("done", "h264"), r["note"])
        self.assertEqual(streams(r["output"])[0]["codec_name"], "h264")

    def test_gif_to_animated_webp(self):
        r = self.run_one("anim.gif", to="webp")
        self.assertEqual(r["status"], "done", r["note"])
        data = Path(r["output"]).read_bytes()
        self.assertTrue(data.startswith(b"RIFF") and b"ANIM" in data[:64])

    def test_max_size_video_two_pass(self):
        # The limit sits below what the quality preset produces, so the two-pass path must run.
        for target in ("hevc", "h264"):
            with self.subTest(target=target):
                preset_size = self.run_one("noise.mov", to=target, force=True)["after"]
                limit = int(preset_size * 0.6)
                r = self.run_one("noise.mov", to=target, max_size=limit, force=True)
                self.assertEqual(r["status"], "done", r["note"])
                self.assertLessEqual(r["after"], limit)

    def test_max_size_too_small_fails_plainly(self):
        r = self.run_one("noise.mov", max_size=20 * 1024)
        self.assertEqual(r["status"], "failed")
        self.assertIn("raise the limit", r["note"])
        self.assertEqual(list(self.out.iterdir()), [])

    def test_max_size_image_walks_the_ladder(self):
        r = self.run_one("photo.png", max_size=12 * 1024)
        self.assertEqual(r["status"], "done", r["note"])
        self.assertLessEqual(r["after"], 12 * 1024)

    def test_max_size_rejects_av1(self):
        r = self.run_one("video.mov", to="av1", max_size=10 * 1024 ** 2)
        self.assertEqual(r["status"], "failed")
        self.assertIn("hevc and h264", r["note"])

    def test_existing_output_is_kept_unless_forced(self):
        first = self.run_one("photo.png")
        stamp = Path(first["output"]).stat().st_mtime_ns
        again = self.run_one("photo.png")
        self.assertEqual(again["status"], "exists")
        self.assertEqual(Path(first["output"]).stat().st_mtime_ns, stamp)
        self.assertEqual(self.run_one("photo.png", force=True)["status"], "done")

    def test_force_replaces_a_symlink_not_its_target(self):
        bystander = self.out / "bystander.txt"
        bystander.write_text("keep me")
        (self.out / "photo_small.jpg").symlink_to(bystander)
        r = self.run_one("photo.png", force=True)
        self.assertEqual(r["status"], "done", r["note"])
        self.assertEqual(bystander.read_text(), "keep me")
        self.assertFalse((self.out / "photo_small.jpg").is_symlink())

    def test_output_symlinked_to_the_source_is_refused(self):
        src = self.out / "clip.png"
        shutil.copy(FIX / "photo.png", src)
        (self.out / "clip_small.jpg").symlink_to(src)
        r = cm.compress(src, None, "medium", 0, None, True, False)
        self.assertEqual(r["status"], "failed")
        self.assertIn("would replace a source file", r["note"])
        self.assertEqual(digest(src), digest(FIX / "photo.png"))

    def test_dangling_symlink_output_needs_force(self):
        (self.out / "photo_small.jpg").symlink_to(self.out / "nowhere.jpg")
        self.assertEqual(self.run_one("photo.png")["status"], "exists")

    def test_location_is_dropped_and_the_date_kept(self):
        r = self.run_one("geo.mov", to="h264")
        self.assertEqual(r["status"], "done", r["note"])
        tags = format_tags(r["output"])
        self.assertFalse([k for k, v in tags.items() if "12.3456" in v], tags)
        self.assertTrue(tags.get("creation_time", "").startswith("2020-01-02"), tags)

    def test_unsupported_file(self):
        txt = self.out / "notes.txt"
        txt.write_text("hello")
        r = cm.compress(txt, None, "medium", 0, None, False, False)
        self.assertEqual(r["status"], "unsupported")


