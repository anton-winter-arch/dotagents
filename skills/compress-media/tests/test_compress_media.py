class TestParseSize(unittest.TestCase):
    def test_units(self):
        self.assertEqual(cm.parse_size("25MB"), 25 * 1024 ** 2)
        self.assertEqual(cm.parse_size("25m"), 25 * 1024 ** 2)
        self.assertEqual(cm.parse_size("500KB"), 500 * 1024)
        self.assertEqual(cm.parse_size("1.5GB"), int(1.5 * 1024 ** 3))
        self.assertEqual(cm.parse_size("8MiB"), 8 * 1024 ** 2)
        self.assertEqual(cm.parse_size("900B"), 900)

