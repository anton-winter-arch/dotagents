def ff(*args):
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args], check=True, stdin=subprocess.DEVNULL)


def format_tags(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_format", "-of", "json", str(path)],
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)["format"].get("tags", {})


def streams(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_streams", "-of", "json", str(path)],
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)["streams"]


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def add_exif_orientation(src: Path, dst: Path, orientation: int) -> None:
    """Copy a JPEG, inserting an EXIF block whose only tag is Orientation."""
    tiff = (b"MM\x00\x2a" + struct.pack(">I", 8) + struct.pack(">H", 1)
            + struct.pack(">HHIHH", 0x0112, 3, 1, orientation, 0) + struct.pack(">I", 0))
    app1 = b"Exif\x00\x00" + tiff
    data = src.read_bytes()
    dst.write_bytes(data[:2] + b"\xff\xe1" + struct.pack(">H", len(app1) + 2) + app1 + data[2:])


