class TestBudgets(unittest.TestCase):
    def test_video_split(self):
        video, audio = cm.video_budget(25 * 1024 ** 2, 60, True, 128)
        total = 25 * 1024 ** 2 * 8 / 1000 / 60 * cm.HEADROOM
        self.assertEqual(audio, 128)
        self.assertAlmostEqual(video + audio, total, delta=1)

    def test_tight_budget_shrinks_audio_first(self):
        video, audio = cm.video_budget(1024 ** 2, 40, True, 128)  # about 199 kbps in total
        self.assertEqual(audio, 64)
        self.assertGreaterEqual(video, cm.MIN_VIDEO_KBPS)

    def test_impossible_budget(self):
        with self.assertRaisesRegex(cm.MediaError, "unwatchable"):
            cm.video_budget(100 * 1024, 600, True, 128)
        with self.assertRaisesRegex(cm.MediaError, "duration is unknown"):
            cm.video_budget(10 * 1024 ** 2, 0, False, 0)

    def test_audio_budget(self):
        self.assertEqual(cm.audio_budget(100 * 1024 ** 2, 60, "aac", 128), 128)
        self.assertLess(cm.audio_budget(1024 ** 2, 120, "aac", 128), 128)
        with self.assertRaisesRegex(cm.MediaError, "at least"):
            cm.audio_budget(10 * 1024, 600, "mp3", 128)


